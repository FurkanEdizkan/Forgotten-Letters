/** The size of a file in plain units. */
export const fileSize = (bytes: number) =>
	bytes < 1024
		? `${bytes} B`
		: bytes < 1024 ** 2
			? `${(bytes / 1024).toFixed(0)} KB`
			: `${(bytes / 1024 ** 2).toFixed(1)} MB`;
