import type { Doc, Facts } from './extract.ts';
import { ownerOf, type Model } from './model.ts';

const HEADER = `// Generated by \`atlas update\` from the code. Don't edit: change the code, or the curated model it hangs from.\n`;
const q = (s: string) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const name = (prefix: string, s: string) => `${prefix}_${s.replace(/[^a-zA-Z0-9]+/g, '_').replace(/^_|_$/g, '') || 'root'}`;
const arr = (xs: string[]) => `[${xs.map(q).join(', ')}]`;

/** The handlers of a route in a stable order: methods, then form actions (as `action:name`). */
export const handlers = (r: Facts['routes'][number]) => [...r.methods, ...r.actions.map((a) => `action:${a}`)];

/** One documented handler as description lines: `GET: summary`, then its Who/In/Out/Errors. */
const docLines = (key: string, d: Doc) =>
	[`${key}: ${d.summary}`, ...(['Who', 'In', 'Out', 'Errors'] as const).filter((t) => d[t.toLowerCase() as keyof Doc]).map((t) => `  ${t}: ${d[t.toLowerCase() as keyof Doc]}`)];

/**
 * The mechanical part of the model, as LikeC4 source (file name → text):
 * - routes.c4: one element per route folder (pages, layouts, endpoints, actions) under the curated element owning it,
 *   with an `imports` relationship to each curated element its files import;
 * - tables.c4: one element per table under the group that lists it in `tables`.
 * Only curated elements are consulted, so the output depends on the code and the curated model alone.
 */
export function generate(facts: Facts, model: Model, routesDir = ''): Record<string, string> {
	const curated = model.elements.filter((e) => !e.generated);
	const importsOf = new Map(facts.modules.map((m) => [m.path, m.imports]));

	const byParent = new Map<string, string[]>();
	const rels: string[] = [];
	for (const r of facts.routes) {
		const parent = ownerOf(r.files[0], curated);
		if (!parent) continue; // reported by `check` as an unowned file
		const id = name('route', routesDir ? r.dir.slice(routesDir.length) : r.dir);
		const endpoint = r.files.every((f) => /\/\+server\.[jt]s$/.test(f));
		const page = r.files.some((f) => /\/\+page[^/]*\.svelte$/.test(f));
		const what = [
			r.methods.length ? r.methods.join(' ') : '',
			r.actions.length ? `actions: ${r.actions.join(', ')}` : '',
			!page && !endpoint ? 'layout' : ''
		].filter(Boolean);
		const documented = handlers(r).filter((h) => r.docs?.[h]).flatMap((h) => docLines(h, r.docs[h]));
		const description = [what.join(' · '), ...documented].filter(Boolean).join('\n');
		const body = [
			description ? `      description ${q(description)}` : '',
			`      metadata {\n        generated 'true'\n        route ${q(r.route)}\n        code ${arr(r.files)}\n      }`
		].filter(Boolean);
		(byParent.get(parent.id) ?? byParent.set(parent.id, []).get(parent.id)!).push(
			`    ${id} = ${endpoint ? 'endpoint' : 'page'} ${q(r.route)} {\n${body.join('\n')}\n    }`
		);
		const targets = new Set<string>();
		for (const f of r.files)
			for (const t of importsOf.get(f) ?? []) {
				const to = ownerOf(t, curated);
				if (to && to.id !== parent.id && !to.id.startsWith(parent.id + '.')) targets.add(to.id);
			}
		for (const t of [...targets].sort()) rels.push(`  ${parent.id}.${id} -[imports]-> ${t} {\n    metadata { generated 'true' }\n  }`);
	}
	const routes = [...byParent].map(([parent, els]) => `  extend ${parent} {\n${els.join('\n')}\n  }`);

	const tables = curated
		.filter((e) => e.tables.length)
		.map((g) => {
			const present = new Set(facts.tables.map((t) => t.name));
			const els = g.tables.filter((t) => present.has(t)).map((t) => `    ${name('table', t)} = table ${q(t)} {\n      metadata { generated 'true' }\n    }`);
			return els.length ? `  extend ${g.id} {\n${els.join('\n')}\n  }` : '';
		})
		.filter(Boolean);

	const file = (blocks: string[]) => `${HEADER}model {\n${blocks.join('\n\n')}\n}\n`;
	return { 'routes.c4': file([...routes, ...rels]), 'tables.c4': file(tables) };
}
