import { posix } from 'node:path';
import type { Facts } from './extract.ts';
import { ownerOf, summary, within, type El, type Model } from './model.ts';

/** The curated element a (possibly generated) element sits in. */
const curatedOf = (id: string, byId: Map<string, El>) => {
	let e = byId.get(id);
	while (e?.generated && e.parent) e = byId.get(e.parent);
	return e?.id ?? id;
};

/** Files as `dir/ a.ts b.ts`, one group per folder. */
function files(paths: string[]) {
	const byDir = new Map<string, string[]>();
	for (const p of paths.sort()) (byDir.get(posix.dirname(p)) ?? byDir.set(posix.dirname(p), []).get(posix.dirname(p))!).push(posix.basename(p));
	return [...byDir].map(([d, names]) => `${d}/ ${names.join(' ')}`).join('; ');
}

/** The shortest tail of each id that is still unique (`cf.app.server.auth` → `server.auth` when another `auth` exists). */
export function shortIds(ids: string[]) {
	const short = new Map<string, string>();
	for (const id of ids) {
		const parts = id.split('.');
		for (let n = 1; n <= parts.length; n++) {
			const tail = parts.slice(-n).join('.');
			if (ids.filter((o) => o === tail || o.endsWith('.' + tail)).length === 1) {
				short.set(id, tail);
				break;
			}
		}
	}
	return (id: string) => short.get(id) ?? id;
}

/** Curated-level dependencies: generated relationships are lifted to the curated elements holding their ends. */
export function dependencies(model: Model) {
	const byId = new Map(model.elements.map((e) => [e.id, e]));
	const pairs = new Map<string, { source: string; target: string; title: string }>();
	for (const r of model.relationships) {
		const source = curatedOf(r.source, byId), target = curatedOf(r.target, byId);
		if (within(source, target) || within(target, source)) continue;
		const key = `${source} ${target}`;
		const prev = pairs.get(key);
		if (!prev || (!prev.title && r.title)) pairs.set(key, { source, target, title: r.title });
	}
	return [...pairs.values()];
}

/**
 * MAP.md: the whole architecture in a few kilobytes, for a person or an agent to read before touching code.
 * Every curated element with its files and neighbours, the routes under it, the table groups, and each feature's flow.
 */
export function renderMap(model: Model, facts: Facts, modelDir: string): string {
	const curated = model.elements.filter((e) => !e.generated);
	const deps = dependencies(model);
	const short = shortIds(curated.map((e) => e.id));
	const ownedFiles = new Map<string, string[]>();
	const routeFiles = new Set(facts.routes.flatMap((r) => r.files));
	for (const m of facts.modules) {
		if (routeFiles.has(m.path) || /\.(spec|test)\.[jt]s$/.test(m.path)) continue; // routes are listed as routes; tests sit beside their module
		const o = ownerOf(m.path, curated);
		if (o) (ownedFiles.get(o.id) ?? ownedFiles.set(o.id, []).get(o.id)!).push(m.path);
	}
	// A route's handlers with their doc summaries: `GET (List items) DELETE · actions: reset (Resets it)`.
	const routeLine = new Map(
		facts.routes.map((r) => {
			const s = (h: string) => (r.docs?.[h]?.summary ? ` (${r.docs[h].summary})` : '');
			const bits = [r.methods.map((m) => m + s(m)).join(' '), r.actions.length ? `actions: ${r.actions.map((a) => a + s(`action:${a}`)).join(', ')}` : ''];
			return [r.route, bits.filter(Boolean).join(' · ')];
		})
	);
	const routesUnder = new Map<string, El[]>();
	for (const e of model.elements) if (e.generated && e.kind !== 'table' && e.parent) (routesUnder.get(e.parent) ?? routesUnder.set(e.parent, []).get(e.parent)!).push(e);

	const out: string[] = [
		'# Architecture map',
		'',
		`Generated by \`atlas update\` from the LikeC4 model in \`${modelDir}/\`; don't edit. Read this before changing code;`,
		'change the model first when the structure changes. See it drawn: `npm --prefix tools/atlas run serve`. Ask it',
		'questions through the `likec4` MCP server. Under each element, `uses` and `used by` name other elements by the',
		'shortest unique end of their id.',
		'',
		'## Elements',
		''
	];
	for (const e of curated) {
		const depth = e.id.split('.').length - 1;
		const pad = '  '.repeat(depth);
		const uses = deps.filter((d) => d.source === e.id).map((d) => short(d.target));
		const usedBy = deps.filter((d) => d.target === e.id).map((d) => short(d.source));
		const bits = [
			ownedFiles.get(e.id)?.length ? `files: ${files(ownedFiles.get(e.id)!)}` : e.code.length && !e.code.some((c) => facts.modules.some((m) => m.path === c)) ? `code: ${e.code.join(' ')}` : '',
			e.tables.length ? `tables: ${e.tables.join(' ')}` : '',
			uses.length ? `uses: ${uses.join(' ')}` : '',
			usedBy.length ? `used by: ${usedBy.join(' ')}` : ''
		].filter(Boolean);
		out.push(`${pad}- \`${e.id}\` ${e.title}${e.tags.length ? ` #${e.tags.join(' #')}` : ''}${summary(e) ? ` — ${summary(e)}` : ''}`);
		for (const b of bits) out.push(`${pad}  ${b}`);
		const routes = routesUnder.get(e.id);
		// One line: the group's `uses` already sums up what its routes import (each route's own imports: the MCP server).
		if (routes?.length) {
			const list = routes
				.sort((a, b) => a.title.localeCompare(b.title))
				.map((r) => {
					const what = routeLine.get(r.title) || r.description.split('\n')[0];
					return `${r.title}${what ? ` (${what})` : r.kind === 'endpoint' ? ' (endpoint)' : ''}`;
				});
			out.push(`${pad}  routes: ${list.join(' · ')}`);
		}
	}
	const features = model.views.filter((v) => v.dynamic);
	if (features.length) {
		out.push('', '## Features', '');
		for (const v of features) {
			out.push(`### ${v.title} (\`${v.id}\`)`, '');
			const intro = v.description.split('\n\n')[0].trim();
			if (intro) out.push(intro, '');
			v.steps.forEach((s, i) => out.push(`${i + 1}. ${short(s.from)} → ${short(s.to)}${s.label ? `: ${s.label}` : ''}`));
			out.push('');
		}
	}
	return out.join('\n').replace(/\n+$/, '\n');
}

/** map.json: the same, for tools. The raw facts stay in the .atlas cache. */
export function renderJson(model: Model) {
	return JSON.stringify({ elements: model.elements, dependencies: dependencies(model), views: model.views }, null, 1);
}
